"""Generate identical runtime catalogs from SIX ISO 4217 List One XML.
Usage: python3 scripts/sync-accounting-currencies.py /path/to/list-one.xml
Source: https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml
No network or runtime dependency. Non-monetary/test codes without minor units are excluded.
"""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

root = ET.parse(sys.argv[1]).getroot()
rows = {}
for entry in root.findall('.//CcyNtry'):
    code, unit = entry.findtext('Ccy'), entry.findtext('CcyMnrUnts') or ''
    if code and unit.isdigit():
        rows[code] = {'code': code, 'name': entry.findtext('CcyNm'), 'digits': int(unit)}
header = '// Generated by scripts/sync-accounting-currencies.py from SIX ISO 4217 List One.\n'
source = header + f"export const CURRENCY_CATALOG_DATE = '{root.attrib['Pblshd']}';\n"
source += 'export const CURRENCIES = ' + json.dumps(sorted(rows.values(), key=lambda row: row['code']), ensure_ascii=False, indent=2) + ';\n'
source += '''
export const CURRENCY_CODES = CURRENCIES.map(currency => currency.code);
const byCode = new Map(CURRENCIES.map(currency => [currency.code, currency]));
export const isSupportedCurrency = code => byCode.has(code);
export const currencyDigits = code => byCode.get(code)?.digits ?? 2;
export function roundCurrency(amount, code = 'CHF') {
  const factor = 10 ** currencyDigits(code);
  return Math.round((Number(amount || 0) + Number.EPSILON) * factor) / factor;
}
'''
repo = Path(__file__).resolve().parents[1]
for target in ['client/src/shared/data/currencies.js', 'server/src/shared/data/currencies.js']:
    (repo / target).write_text(source)
print(f"Generated {len(rows)} monetary currency/fund codes, published {root.attrib['Pblshd']}")
