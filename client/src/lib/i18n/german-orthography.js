const ORDERED_GERMAN_ORTHOGRAPHY_REPLACEMENTS = [...GERMAN_ORTHOGRAPHY_REPLACEMENTS]
  .sort(([left], [right]) => right.length - left.length);

export function normalizeGermanOrthography(value) {
  if (typeof value !== 'string') return value;
  return ORDERED_GERMAN_ORTHOGRAPHY_REPLACEMENTS.reduce(
    (text, [from, to]) => text.split(from).join(to),
    value,
  );
}
