'use client';
import { useState } from 'react';
import { PageHeader } from '@/shared/components/page-header';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { DocumentsTable } from '@/modules/doctpl/components/DocumentsTable';
import { DocumentPreviewDrawer } from '@/modules/doctpl/components/DocumentPreviewDrawer';
import { useDocuments } from '@/modules/doctpl/hooks/useDocumentQueries';
import { useDownloadDocument } from '@/modules/doctpl/hooks/useDocumentMutations';

const DOC_TYPES = [
  ['all', 'All Types'],
  ['quotation', 'Quotation'],
  ['order_confirmation', 'Order Confirmation'],
  ['invoice_standard', 'Invoice'],
  ['invoice_advance', 'Advance Invoice'],
  ['invoice_final', 'Final Invoice'],
  ['cover_letter', 'Cover Letter'],
  ['service_report', 'Service Report'],
  ['inspection_certificate', 'Inspection Certificate'],
];

export default function DocumentsPage() {
  const [typeFilter, setTypeFilter] = useState('all');
  const [preview, setPreview] = useState(null);
  const { data, isLoading } = useDocuments(typeFilter !== 'all' ? { documentType: typeFilter } : {});
  const download = useDownloadDocument();
  const documents = data?.items ?? [];

  const handlePreview = async (doc) => {
    const r = await download.mutateAsync(doc._id);
    setPreview({ url: r?.data?.downloadUrl, fileName: doc.fileName });
  };

  const handleDownload = async (doc) => {
    const r = await download.mutateAsync(doc._id);
    if (r?.data?.downloadUrl) window.open(r.data.downloadUrl, '_blank');
  };

  return (
    <div className="flex flex-col gap-6 p-6">
      <PageHeader
        title="Generated Documents"
        description="All PDFs generated by the system"
      />
      <div className="flex gap-3">
        <Select value={typeFilter} onValueChange={setTypeFilter}>
          <SelectTrigger className="w-52">
            <SelectValue placeholder="Filter by type" />
          </SelectTrigger>
          <SelectContent>
            {DOC_TYPES.map(([val, label]) => (
              <SelectItem key={val} value={val}>{label}</SelectItem>
            ))}
          </SelectContent>
        </Select>
      </div>
      <DocumentsTable
        documents={documents}
        loading={isLoading}
        onPreview={handlePreview}
        onDownload={handleDownload}
      />
      <DocumentPreviewDrawer
        open={!!preview}
        url={preview?.url}
        fileName={preview?.fileName}
        onClose={() => setPreview(null)}
      />
    </div>
  );
}
