// languages with more plural forms (Arabic: _zero/_two/_few/_many) can add them.
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> } & {
  [plural: string]: unknown;
};
export type Translations = Widen<typeof en>;
