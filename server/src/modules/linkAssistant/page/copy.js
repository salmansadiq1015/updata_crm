// Wording only the voice call screen uses (everything after the "Voice call screen" marker).
const VOICE_KEYS = new Set(Object.keys(PAGE_COPY.en).slice(Object.keys(PAGE_COPY.en).indexOf('vKicker')));

/** Copy for the languages a campaign offers (keeps the bootstrap small; voice wording only with the call screen). */
export const pageCopyFor = (languages = ['en'], { voice = false } = {}) => Object.fromEntries(
  [...new Set(['en', ...languages])].filter((l) => PAGE_COPY[l]).map((l) => [l, voice
    ? PAGE_COPY[l]
    : Object.fromEntries(Object.entries(PAGE_COPY[l]).filter(([k]) => !VOICE_KEYS.has(k)))]),
);
