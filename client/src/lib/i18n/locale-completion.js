function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function preserveCase(source, translated) {
  if (!source || !translated) return translated;
  if (source === source.toUpperCase()) return translated.toUpperCase();
  if (source[0] === source[0].toUpperCase()) {
    return `${translated[0]?.toUpperCase() ?? ''}${translated.slice(1)}`;
  }
  return translated;
}

function translateSegment(segment, locale) {
  if (!segment || !WORDS[locale]) return segment;

  const exact = EXACT[locale].get(segment.trim());
  if (exact) return segment.replace(segment.trim(), exact);

  let output = segment;
  for (const [source, target] of PHRASES[locale]) {
    output = output.replace(new RegExp(escapeRegExp(source), 'gi'), (match) =>
      locale === 'fr' ? preserveCase(match, target) : target,
    );
  }

  output = output.replace(/\b[A-Za-z][A-Za-z-]*\b/g, (word) => {
    const translated = WORDS[locale][word.toLowerCase()];
    if (!translated) return word;
    return locale === 'fr' ? preserveCase(word, translated) : translated;
  });

  return output;
}

export function localizeFallback(value, locale) {
  if (typeof value !== 'string') return value;
  if (locale !== 'fr' && locale !== 'ar') return value;

  return value
    .split(TOKEN_PATTERN)
    .map((part) => (part.startsWith('{') && part.endsWith('}') ? part : translateSegment(part, locale)))
    .join('');
}

export function completeLocale(baseLocale, overrides, locale) {
  const completed = {};
  for (const [key, value] of Object.entries(baseLocale)) {
    completed[key] = overrides?.[key] ?? localizeFallback(value, locale);
  }
  return { ...completed, ...overrides };
}
